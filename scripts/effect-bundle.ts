// Builds defaults/lib/effect: the `effect` package's two entry points the
// mods import, `effect` and `effect/http`, bundled from node_modules (the
// exact version in package.json) with their shared code split into one
// chunk. The app serves them as library modules (@fireflies/kit's
// docs/effect-mods.md): one copy evaluated per window for every mod.
//
//   bun scripts/effect-bundle.ts          write defaults/lib/effect
//   bun scripts/effect-bundle.ts --check  fail if it differs from a fresh build
//
// Run it after changing the `effect` version in package.json, and commit the
// result; scripts/effect-bundle.test.ts checks they agree.
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";

const root = join(import.meta.dir, "..");
const dist = join(root, "node_modules/effect/dist");
const out = join(root, "defaults/lib/effect");
const version = JSON.parse(readFileSync(join(root, "node_modules/effect/package.json"), "utf8")).version as string;

/** The bundle's files, by path under defaults/lib/effect. */
export async function build(): Promise<Map<string, string>> {
  const tmp = mkdtempSync(join(tmpdir(), "effect-bundle-"));
  try {
    const result = await Bun.build({
      entrypoints: [join(dist, "index.js"), join(dist, "http/index.js")],
      root: dist,
      outdir: tmp,
      splitting: true,
      format: "esm",
      target: "browser",
      minify: true,
      naming: { entry: "[dir]/[name].[ext]", chunk: "chunk-[hash].[ext]" },
    });
    if (!result.success) throw new Error(result.logs.map(String).join("\n"));
    const banner = `// effect@${version} (MIT, Effectful Technologies Inc.): generated by scripts/effect-bundle.ts, don't edit.\n`;
    const files = new Map<string, string>();
    const walk = (dir: string) => {
      for (const name of readdirSync(dir, { withFileTypes: true })) {
        const path = join(dir, name.name);
        if (name.isDirectory()) walk(path);
        else files.set(relative(tmp, path), banner + readFileSync(path, "utf8"));
      }
    };
    walk(tmp);
    return files;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  const files = await build();
  const now = existsSync(out) ? readdirSync(out, { recursive: true }).map(String).filter((f) => f.endsWith(".js")) : [];
  if (process.argv.includes("--check")) {
    const same = files.size === now.length && [...files].every(([f, text]) => existsSync(join(out, f)) && readFileSync(join(out, f), "utf8") === text);
    if (!same) {
      console.error("defaults/lib/effect differs from a fresh build of node_modules/effect: run bun scripts/effect-bundle.ts");
      process.exit(1);
    }
  } else {
    rmSync(out, { recursive: true, force: true });
    for (const [f, text] of files) {
      mkdirSync(join(out, f, ".."), { recursive: true });
      writeFileSync(join(out, f), text);
    }
    writeFileSync(join(out, "LICENSE"), readFileSync(join(root, "node_modules/effect/LICENSE"), "utf8"));
    console.log([...files].map(([f, t]) => `${f} ${t.length}`).join("\n"));
  }
}
